// ── Load .env ────────────────────────────────────────────────────────────────
function loadDotEnv() {
    try {
        const text = readFileSync('.env', 'utf8');
        for (const line of text.split('\n')) {
            const m = line.match(/^([A-Z0-9_]+)=([\s\S]*?)[\s]*$/);
            if (m) process.env[m[1]] = m[2].trim().replace(/^["']|["']$/g, '');
        }
    } catch { /* ignore */ }
}

loadDotEnv();

const NEO4J_URI  = process.env['NEO4J_URI']!;
const NEO4J_USER = process.env['NEO4J_USERNAME']!;
const NEO4J_PASS = process.env['NEO4J_PASSWORD']!;
const NEO4J_DB   = process.env['NEO4J_DATABASE'];

const driver = neo4j.driver(NEO4J_URI, neo4j.auth.basic(NEO4J_USER, NEO4J_PASS));

function session() {
    return driver.session({ database: NEO4J_DB });
}

function tavusClient(): TavusClient {
    const apiKey = process.env['TAVUS_KEY'];
    if (!apiKey) {
        throw new Error('Missing TAVUS_KEY. Add it to .env to enable Tavus endpoints.');
    }
    return new TavusClient(apiKey);
}

function slugify(value: string): string {
    return value
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/(^-|-$)/g, '');
}

function buildBriefMarkdown(payload: {
    phrase: string;
    recommendation: string;
    stats: {
        momentum: string;
        action: string;
        momentumScore?: number;
        decayRisk?: number;
        opportunityFit?: number;
        actionPriority?: number;
        jellyCount?: number;
        avgHoursOld?: number;
    };
    neighbors: Array<{ phrase: string; momentum: string; score?: number; coWeight?: number }>;
    topJellies: Array<{ title?: string; creator?: string; views?: number; likes?: number; comments?: number; velocity?: number }>;
}) {
    const momentumScore = payload.stats.momentumScore ?? 0;
    const decayRisk = payload.stats.decayRisk ?? 0;
    const opportunityFit = payload.stats.opportunityFit ?? 0;
    const actionPriority = payload.stats.actionPriority ?? 0;
    const jellyCount = payload.stats.jellyCount ?? 0;
    const avgHoursOld = payload.stats.avgHoursOld ?? 0;

    return `# Influencer Trend Brief: ${payload.phrase}

Generated by Boostr Momentum Engine.

## Snapshot
- Phrase: ${payload.phrase}
- Momentum: ${payload.stats.momentum}
- Recommended Action: ${payload.stats.action}
- Momentum Score: ${momentumScore.toFixed(3)}
- Decay Risk: ${(decayRisk * 100).toFixed(1)}%
- Opportunity Fit: ${(opportunityFit * 100).toFixed(1)}%
- Action Priority: ${actionPriority.toFixed(3)}
- Supporting Jellies: ${jellyCount}
- Average Content Age: ${avgHoursOld.toFixed(1)} hours

## Recommended Creator Strategy
${payload.recommendation}

## Suggested Content Angles
${payload.neighbors.slice(0, 8).map((n, idx) =>
`- Angle ${idx + 1}: Pair "${payload.phrase}" with "${n.phrase}" (${n.momentum}, co-occurs ${n.coWeight ?? 0}x).`).join('\n')}

## High-Performing Example Jellies
${payload.topJellies.slice(0, 8).map((j, idx) =>
`- Example ${idx + 1}: ${j.title ?? 'Untitled'} by @${j.creator ?? 'unknown'} (views: ${j.views ?? 0}, likes: ${j.likes ?? 0}, comments: ${j.comments ?? 0}, velocity: ${(j.velocity ?? 0).toFixed(2)}/h).`).join('\n')}

## Creator Prompt Template
Use this briefing to coach a creator:
"You are a trend-aware content strategist. Create 3 short-form video concepts based on phrase '${payload.phrase}', prioritize hooks that match ${payload.stats.momentum} momentum, and incorporate one co-occurring phrase from this list: ${payload.neighbors.slice(0, 5).map(n => n.phrase).join(', ')}. For each concept, include hook, talking points, and caption keywords."
`;
}

