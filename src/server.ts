// ── API: Generate trend brief from graph + optionally push to Tavus KB ─────
app.post('/api/tavus/brief/:phrase', async (req, res) => {
    const phrase = decodeURIComponent(req.params['phrase']!);
    const s = session();

    try {
        const jellyRes = await s.run(`
            MATCH (j:Jelly)-[:MENTIONS]->(p:Phrase {text: $phrase})
            MATCH (c:Creator)-[:POSTED]->(j)
            RETURN j.title AS title, j.views AS views, j.likes AS likes, j.comments AS comments,
                   j.velocity AS velocity, c.username AS creator
            ORDER BY j.success DESC LIMIT 8
        `, { phrase });

        const neighborsRes = await s.run(`
            MATCH (p:Phrase {text: $phrase})-[r:CO_OCCURS_WITH]-(n:Phrase)
            RETURN n.text AS phrase, n.momentum AS momentum, n.weightedScore AS score, r.weight AS coWeight
            ORDER BY r.weight DESC, n.weightedScore DESC LIMIT 8
        `, { phrase });

        const statRes = await s.run(`
            MATCH (p:Phrase {text: $phrase})
            RETURN p.momentum AS momentum,
                   p.action AS action,
                   p.momentumScore AS momentumScore,
                   p.decayRisk AS decayRisk,
                   p.opportunityFit AS opportunityFit,
                   p.actionPriority AS actionPriority,
                   p.jellyCount AS jellyCount,
                   p.avgHoursOld AS avgHoursOld
        `, { phrase });

        if (!statRes.records[0]) {
            return res.status(404).json({ error: `Phrase "${phrase}" not found in graph.` });
        }

        const neighbors = neighborsRes.records.map(r => ({
            phrase: r.get('phrase') as string,
            momentum: r.get('momentum') as string,
            score: (r.get('score') as number | null) ?? 0,
            coWeight: (r.get('coWeight') as number | null) ?? 0,
        }));

        const topJellies = jellyRes.records.map(r => ({
            title: r.get('title') as string,
            views: (r.get('views') as number | null) ?? 0,
            likes: (r.get('likes') as number | null) ?? 0,
            comments: (r.get('comments') as number | null) ?? 0,
            velocity: (r.get('velocity') as number | null) ?? 0,
            creator: r.get('creator') as string,
        }));

        const stat = statRes.records[0];
        const stats = {
            momentum: (stat.get('momentum') as string | null) ?? 'stable',
            action: (stat.get('action') as string | null) ?? 'remix',
            momentumScore: (stat.get('momentumScore') as number | null) ?? 0,
            decayRisk: (stat.get('decayRisk') as number | null) ?? 0,
            opportunityFit: (stat.get('opportunityFit') as number | null) ?? 0,
            actionPriority: (stat.get('actionPriority') as number | null) ?? 0,
            jellyCount: (stat.get('jellyCount') as number | null) ?? 0,
            avgHoursOld: (stat.get('avgHoursOld') as number | null) ?? 0,
        };

        const recommendation =
            stats.action === 'double_down'
                ? `Double down now: create a post on "${phrase}" within 6 hours and pair with a rising co-topic.`
                : stats.action === 'collaborate'
                    ? `Collaborate injection: keep "${phrase}" alive by featuring a collaborator and cross-audience hook.`
                    : stats.action === 'retire'
                        ? `Retire topic: "${phrase}" is cooling. Shift to a neighboring phrase with stronger momentum.`
                        : `Remix / clip refresh: reframe "${phrase}" with a fresh hook and new phrasing combo.`;

        const markdown = buildBriefMarkdown({
            phrase,
            recommendation,
            stats,
            neighbors,
            topJellies,
        });

        const now = new Date().toISOString().replace(/[:.]/g, '-');
        const fileName = `${slugify(phrase)}-${now}.md`;
        const kbDir = path.join(__dirname, '..', 'public', 'kb');
        mkdirSync(kbDir, { recursive: true });
        writeFileSync(path.join(kbDir, fileName), markdown, 'utf8');

        const providedBaseUrl = req.body?.base_url;
        const envBaseUrl = process.env['TAVUS_PUBLIC_BASE_URL'];
        const publicBase = (typeof providedBaseUrl === 'string' && providedBaseUrl) || envBaseUrl;
        const localPath = `/kb/${fileName}`;
        const documentUrl = publicBase ? `${publicBase.replace(/\/$/, '')}${localPath}` : null;

        let tavusDocument: unknown = null;
        const shouldCreateDocument = Boolean(req.body?.create_document);
        if (shouldCreateDocument) {
            if (!documentUrl) {
                return res.status(400).json({
                    error: 'create_document=true requires a public base URL (body.base_url or TAVUS_PUBLIC_BASE_URL).',
                    local_path: localPath,
                    markdown,
                });
            }
            const client = tavusClient();
            tavusDocument = await client.createDocument({
                document_url: documentUrl,
                document_name: `Trend Brief: ${phrase}`,
                tags: ['boostr', 'momentum', slugify(phrase)],
            });
        }

        return res.json({
            phrase,
            local_path: localPath,
            document_url: documentUrl,
            markdown,
            tavus_document: tavusDocument,
        });
    } catch (err) {
        const message = err instanceof Error ? err.message : String(err);
        return res.status(500).json({ error: message });
    } finally {
        await s.close();
    }
});

// ── Script builder ────────────────────────────────────────────────────────────
function buildVideoScript(payload: {
    phrase: string;
    momentum: string;
    action: string;
    momentumScore: number;
    decayRisk: number;
    jellyCount: number;
    avgHoursOld: number;
    neighbors: Array<{ phrase: string; momentum: string }>;
    topJelly: { title?: string; creator?: string; views?: number } | null;
}): string {
    const { phrase, momentum, action, momentumScore, decayRisk, jellyCount, avgHoursOld, neighbors, topJelly } = payload;

    const score = (momentumScore * 100).toFixed(0);
    const decay = (decayRisk * 100).toFixed(0);
    const age   = avgHoursOld.toFixed(0);

    const risingNeighbors = neighbors
        .filter(n => n.momentum === 'rising' || n.momentum === 'stable')
        .slice(0, 2)
        .map(n => n.phrase);

    const neighborLine = risingNeighbors.length > 0
        ? `The strongest angles to pair with this are "${risingNeighbors[0]}"${risingNeighbors[1] ? ` and "${risingNeighbors[1]}"` : ''}.`
        : '';

    const actionLine: Record<string, string> = {
        double_down: `Your move is to post now — this window is open and the velocity is holding.`,
        collaborate: `Your move is a collab injection — bring in another creator to extend the cycle before it peaks.`,
        remix:       `Your move is a remix or clip refresh — reframe this topic with a new hook before the window closes.`,
        retire:      `This topic is cooling. Pivot to a neighboring phrase with stronger momentum instead.`,
    };

    const topJellyLine = topJelly?.title
        ? `The top performing jelly right now is "${topJelly.title}"${topJelly.creator ? ` by @${topJelly.creator}` : ''}${topJelly.views ? `, pulling ${topJelly.views.toLocaleString()} views` : ''}.`
        : '';

    return [
        `Hey — Boostr just flagged "${phrase}" as ${momentum} with a momentum score of ${score} out of 100.`,
        `${jellyCount} jellies have posted on this topic in the last ${age} hours, and decay risk is sitting at ${decay} percent.`,
        topJellyLine,
        neighborLine,
        actionLine[action] ?? actionLine['remix'],
        `This is your Boostr daily brief. Stay ahead of the trend.`,
    ].filter(Boolean).join(' ');
}

// ── Coach context builder ─────────────────────────────────────────────────────
function buildCoachContext(phrases: Array<{
    phrase: string;
    momentum: string;
    action: string;
    momentumScore: number;
    decayRisk: number;
    jellyCount: number;
    avgHoursOld: number;
    neighbors: string[];
}>): string {
    const rising   = phrases.filter(p => p.momentum === 'rising');
    const stable   = phrases.filter(p => p.momentum === 'stable');
    const decaying = phrases.filter(p => p.momentum === 'decaying');

    const actionLabel: Record<string, string> = {
        double_down: 'POST NOW',
        collaborate: 'COLLABORATE',
        remix:       'REMIX',
        retire:      'SKIP',
    };

    function fmtPhrase(p: typeof phrases[0]): string {
        const score = (p.momentumScore * 100).toFixed(0);
        const decay = (p.decayRisk * 100).toFixed(0);
        const label = actionLabel[p.action] ?? p.action;
        const base  = `- "${p.phrase}"  [${label}]  momentum:${score}/100  decay:${decay}%  ${p.jellyCount} jellies  avg ${p.avgHoursOld.toFixed(0)}h old`;
        const pairs = p.neighbors.length > 0
            ? `\n  → Pair with: ${p.neighbors.map(n => `"${n}"`).join(', ')}`
            : '';
        return base + pairs;
    }

    const ts = new Date().toLocaleString('en-US', {
        month: 'short', day: 'numeric',
        hour: 'numeric', minute: '2-digit',
    });

    return [
        'You are Boostr — a sharp, enthusiastic JellyJelly social media coach.',
        'You hold real-time trend intelligence scraped from the JellyJelly platform.',
        '',
        'INSTRUCTION: Open by asking "What do you usually post about?" in a warm, natural tone.',
        'Once the creator tells you their niche, match it to the trending topics below.',
        'Recommend 2–3 specific video concepts. Each concept needs: one hook line, 2–3 talking',
        'points, and 3–5 caption hashtags. Be direct and specific — no generic tips.',
        '',
        `## LIVE JELLYJELLY TREND DATA — ${ts}`,
        '',
        `### RISING  (${rising.length} topics — 6-hour window)`,
        rising.length > 0 ? rising.map(fmtPhrase).join('\n') : '(none currently rising)',
        '',
        `### STABLE  (${stable.length} topics — solid foundations)`,
        stable.length > 0 ? stable.slice(0, 6).map(fmtPhrase).join('\n') : '(none)',
        '',
        `### FADING  (${decaying.length} topics — steer clear unless remixing)`,
        decaying.length > 0
            ? decaying.slice(0, 4).map(p => `- "${p.phrase}"  momentum:${(p.momentumScore * 100).toFixed(0)}/100  cooling`).join('\n')
            : '(none)',
    ].join('\n');
}

// ── API: start a live coach session (Tavus conversation + live trend context) ─
app.post('/api/coach/start', async (req, res) => {
    const s = session();
    try {
        const topRes = await s.run(`
            MATCH (p:Phrase)
            WHERE p.jellyCount >= 2
            RETURN p.text AS phrase,
                   p.momentum AS momentum,
                   p.action AS action,
                   p.momentumScore AS momentumScore,
                   p.decayRisk AS decayRisk,
                   p.opportunityFit AS opportunityFit,
                   p.actionPriority AS actionPriority,
                   p.jellyCount AS jellyCount,
                   p.avgHoursOld AS avgHoursOld
            ORDER BY p.actionPriority DESC
            LIMIT 15
        `);

        if (topRes.records.length === 0) {
            return res.status(503).json({
                error: 'No trend data found. Run the topic_graph pipeline first.',
            });
        }

        const phrases = topRes.records.map(r => ({
            phrase:        r.get('phrase')          as string,
            momentum:      (r.get('momentum')       as string | null) ?? 'stable',
            action:        (r.get('action')         as string | null) ?? 'remix',
            momentumScore: (r.get('momentumScore')  as number | null) ?? 0,
            decayRisk:     (r.get('decayRisk')      as number | null) ?? 0,
            opportunityFit:(r.get('opportunityFit') as number | null) ?? 0,
            actionPriority:(r.get('actionPriority') as number | null) ?? 0,
            jellyCount:    (r.get('jellyCount')     as number | null) ?? 0,
            avgHoursOld:   (r.get('avgHoursOld')    as number | null) ?? 0,
            neighbors:     [] as string[],
        }));

        // Enrich top-3 rising phrases with their strongest co-occurring partners
        const risingTop = phrases.filter(p => p.momentum === 'rising').slice(0, 3);
        await Promise.all(risingTop.map(async p => {
            const nRes = await s.run(`
                MATCH (ph:Phrase {text: $phrase})-[r:CO_OCCURS_WITH]-(n:Phrase)
                WHERE n.momentum IN ['rising', 'stable']
                RETURN n.text AS phrase
                ORDER BY r.weight DESC LIMIT 3
            `, { phrase: p.phrase });
            p.neighbors = nRes.records.map(r => r.get('phrase') as string);
        }));

        const context = buildCoachContext(phrases);

        const client = tavusClient();
        let personaId = process.env['TAVUS_PERSONA_ID'];
        if (!personaId) {
            const pRes = await client.listPersonas();
            personaId = pRes.data[0]?.persona_id;
        }
        if (!personaId) {
            return res.status(500).json({
                error: 'No Tavus persona configured. Add TAVUS_PERSONA_ID to .env or create one at app.tavus.io.',
            });
        }

        const conversation = await client.createConversation({
            persona_id: personaId,
            conversation_name: `Boostr Coach — ${new Date().toISOString().slice(0, 16)}`,
            conversational_context: context,
            custom_greeting: "Hey! I've just loaded today's JellyJelly trend data. What kind of content do you usually create?",
            test_mode: false,
        });

        return res.json({
            conversation_id: conversation.conversation_id,
            conversation_url: conversation.conversation_url,
            phrases_analyzed: phrases.length,
        });
    } catch (err) {
        const message = err instanceof Error ? err.message : String(err);
        return res.status(500).json({ error: message });
    } finally {
        await s.close();
    }
});

// ── API: generate Tavus video brief for a phrase ──────────────────────────────
app.post('/api/tavus/video/:phrase', async (req, res) => {
    const phrase = decodeURIComponent(req.params['phrase']!);
    const { replica_id, fast = true, background_source_url } = req.body ?? {};

    if (!replica_id || typeof replica_id !== 'string') {
        return res.status(400).json({ error: 'replica_id is required in request body' });
    }

    const s = session();
    try {
        const [statRes, neighborRes, jellyRes] = await Promise.all([
            s.run(`
                MATCH (p:Phrase {text: $phrase})
                RETURN p.momentum AS momentum, p.action AS action,
                       p.momentumScore AS momentumScore, p.decayRisk AS decayRisk,
                       p.jellyCount AS jellyCount, p.avgHoursOld AS avgHoursOld
            `, { phrase }),
            s.run(`
                MATCH (p:Phrase {text: $phrase})-[r:CO_OCCURS_WITH]-(n:Phrase)
                RETURN n.text AS phrase, n.momentum AS momentum
                ORDER BY r.weight DESC LIMIT 4
            `, { phrase }),
            s.run(`
                MATCH (j:Jelly)-[:MENTIONS]->(p:Phrase {text: $phrase})
                MATCH (c:Creator)-[:POSTED]->(j)
                RETURN j.title AS title, j.views AS views, c.username AS creator
                ORDER BY j.success DESC LIMIT 1
            `, { phrase }),
        ]);

        if (!statRes.records[0]) {
            return res.status(404).json({ error: `Phrase "${phrase}" not found in graph.` });
        }

        const stat = statRes.records[0];
        const topJellyRec = jellyRes.records[0];

        const script = buildVideoScript({
            phrase,
            momentum:      (stat.get('momentum') as string | null)      ?? 'stable',
            action:        (stat.get('action') as string | null)         ?? 'remix',
            momentumScore: (stat.get('momentumScore') as number | null)  ?? 0,
            decayRisk:     (stat.get('decayRisk') as number | null)      ?? 0,
            jellyCount:    (stat.get('jellyCount') as number | null)     ?? 0,
            avgHoursOld:   (stat.get('avgHoursOld') as number | null)    ?? 0,
            neighbors: neighborRes.records.map(r => ({
                phrase:   r.get('phrase') as string,
                momentum: r.get('momentum') as string,
            })),
            topJelly: topJellyRec ? {
                title:   topJellyRec.get('title') as string,
                creator: topJellyRec.get('creator') as string,
                views:   (topJellyRec.get('views') as number | null) ?? 0,
            } : null,
        });

        const client = tavusClient();
        const video = await client.createVideo({
            replica_id,
            script,
            video_name: `Boostr — ${phrase}`,
            fast: Boolean(fast),
            ...(background_source_url ? { background_source_url } : {}),
        });

        return res.json({ phrase, script, video });
    } catch (err) {
        const message = err instanceof Error ? err.message : String(err);
        return res.status(500).json({ error: message });
    } finally {
        await s.close();
    }
});

