// ── API: graph data ──────────────────────────────────────────────────────────
app.get('/api/graph', async (req, res) => {
    const keyword = (req.query['keyword'] as string) || '';
    const s = session();
    try {
        // Phrase nodes
        const phraseRes = await s.run(`
            MATCH (p:Phrase)
            ${keyword ? 'WHERE p.text CONTAINS $kw' : ''}
            RETURN p.text AS id,
                   p.weightedScore AS score,
                   p.momentum AS momentum,
                   p.jellyCount AS jellyCount,
                   p.avgHoursOld AS avgHoursOld
            ORDER BY p.weightedScore DESC
            LIMIT 80
        `, { kw: keyword.toLowerCase() });

        const nodes = phraseRes.records.map(r => ({
            id: r.get('id') as string,
            type: 'phrase',
            score: (r.get('score') as number) ?? 0,
            momentum: (r.get('momentum') as string) ?? 'stable',
            jellyCount: (r.get('jellyCount') as number) ?? 0,
            avgHoursOld: (r.get('avgHoursOld') as number) ?? 0,
        }));

        const nodeIds = new Set(nodes.map(n => n.id));

        // Co-occurrence edges between those nodes
        const edgeRes = await s.run(`
            MATCH (pa:Phrase)-[r:CO_OCCURS_WITH]-(pb:Phrase)
            WHERE pa.text IN $ids AND pb.text IN $ids
            RETURN pa.text AS source, pb.text AS target, r.weight AS weight
        `, { ids: [...nodeIds] });

        const seen = new Set<string>();
        const links = edgeRes.records
            .map(r => ({
                source: r.get('source') as string,
                target: r.get('target') as string,
                weight: (r.get('weight') as number) ?? 1,
            }))
            .filter(l => {
                const key = [l.source, l.target].sort().join('|||');
                if (seen.has(key)) return false;
                seen.add(key);
                return true;
            });

        res.json({ nodes, links });
    } finally {
        await s.close();
    }
});

// ── API: top jellies for a phrase ────────────────────────────────────────────
app.get('/api/phrase/:phrase', async (req, res) => {
    const phrase = decodeURIComponent(req.params['phrase']!);
    const s = session();
    try {
        // Top jellies mentioning this phrase
        const jellyRes = await s.run(`
            MATCH (j:Jelly)-[:MENTIONS]->(p:Phrase {text: $phrase})
            MATCH (c:Creator)-[:POSTED]->(j)
            RETURN j.id AS id, j.title AS title, j.views AS views,
                   j.likes AS likes, j.comments AS comments,
                   j.success AS success, j.velocity AS velocity,
                   j.postedAt AS postedAt, j.thumbnail AS thumbnail,
                   c.username AS creator
            ORDER BY j.success DESC LIMIT 5
        `, { phrase });

        const jellies = jellyRes.records.map(r => ({
            id: r.get('id'), title: r.get('title'),
            views: r.get('views'), likes: r.get('likes'),
            comments: r.get('comments'), success: r.get('success'),
            velocity: r.get('velocity'), postedAt: r.get('postedAt'),
            thumbnail: r.get('thumbnail'), creator: r.get('creator'),
        }));

        // Co-occurring phrases (neighbors)
        const neighborRes = await s.run(`
            MATCH (p:Phrase {text: $phrase})-[r:CO_OCCURS_WITH]-(n:Phrase)
            RETURN n.text AS phrase, n.momentum AS momentum,
                   n.weightedScore AS score, r.weight AS coWeight
            ORDER BY r.weight DESC, n.weightedScore DESC LIMIT 6
        `, { phrase });

        const neighbors = neighborRes.records.map(r => ({
            phrase: r.get('phrase'), momentum: r.get('momentum'),
            score: r.get('score'), coWeight: r.get('coWeight'),
        }));

        // Phrase stats
        const statRes = await s.run(`
            MATCH (p:Phrase {text: $phrase})
            RETURN p.momentum AS momentum, p.weightedScore AS score,
                   p.jellyCount AS jellyCount, p.avgHoursOld AS avgHoursOld,
                   p.momentumScore AS momentumScore, p.decayRisk AS decayRisk,
                   p.opportunityFit AS opportunityFit, p.actionPriority AS actionPriority,
                   p.action AS action
        `, { phrase });
        const stat = statRes.records[0];

        const risingNeighbors = neighbors
            .filter(n => n.momentum === 'rising' || n.momentum === 'stable')
            .slice(0, 2)
            .map(n => `"${n.phrase}"`)
            .join(' + ');

        const momentum = stat?.get('momentum') ?? 'stable';
        const action   = (stat?.get('action') as string | null) ?? 'remix';
        const avgAge   = (stat?.get('avgHoursOld') as number ?? 0).toFixed(0);

        const ACTION_COPY: Record<string, string> = {
            double_down: `Double down now — post with ${risingNeighbors ? `${risingNeighbors} + ` : ''}"${phrase}" in the next 6 hours. This cluster is rising and avg jelly age is ${avgAge}h.`,
            collaborate: `Collaborate injection — bring in a co-creator around "${phrase}". High momentum but decay is starting; a collab will extend the cycle.`,
            remix:       `Remix / clip refresh — "${phrase}" is ${momentum}. Re-cut existing content with a fresh angle before the window closes.`,
            retire:      `Retire topic — "${phrase}" has low momentum and low audience fit. Pivot to a neighboring rising phrase instead.`,
        };
        const recommendation = ACTION_COPY[action]
            ?? `"${phrase}" is ${momentum}. Combine with ${risingNeighbors || 'a trending neighbor'} to give it a momentum boost.`;

        res.json({
            phrase, jellies, neighbors, recommendation,
            stats: {
                momentum, action, score: stat?.get('score'),
                jellyCount: stat?.get('jellyCount'), avgHoursOld: stat?.get('avgHoursOld'),
                momentumScore: stat?.get('momentumScore'), decayRisk: stat?.get('decayRisk'),
                opportunityFit: stat?.get('opportunityFit'), actionPriority: stat?.get('actionPriority'),
            },
        });
    } finally {
        await s.close();
    }
});

