// ── API: stats summary ────────────────────────────────────────────────────────
app.get('/api/stats', async (req, res) => {
    const s = session();
    try {
        const r = await s.run(`
            MATCH (n) RETURN labels(n)[0] AS label, count(n) AS cnt
        `);
        const counts: Record<string, number> = {};
        r.records.forEach(rec => {
            counts[rec.get('label')] = (rec.get('cnt') as { toNumber(): number }).toNumber();
        });
        const rising = await s.run(`MATCH (p:Phrase {momentum:'rising'}) RETURN count(p) AS cnt`);
        counts['rising_phrases'] = (rising.records[0]?.get('cnt') as { toNumber(): number })?.toNumber() ?? 0;
        res.json(counts);
    } finally {
        await s.close();
    }
});

